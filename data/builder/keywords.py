def match_rule(name: str, rule: dict) -> bool:
    """Чистая проверка одного правила по lower()-имени (см. docstring модуля).

    Совпадение = (любая подстрока contains_any ИЛИ любая И-группа contains_all
    целиком) И ни одна подстрока excludes не встречается.
    """
    s = str(name).lower()
    if any(str(x).lower() in s for x in rule.get("excludes", ())):
        return False
    any_hit = any(str(x).lower() in s for x in rule.get("contains_any", ()))
    all_hit = any(
        all(str(x).lower() in s for x in group)
        for group in rule.get("contains_all", ())
    )
    return any_hit or all_hit



"""Размеры бортов «Конструктора» (дюймы) и привязка моторов к размерам.

Токены SIZE_TOKENS сравниваются как подстроки lower()-имени. «13?9?3» /
«15?7?3» — боевые артефакты кодировки в выгрузке 1С («?» вместо «×»),
обязаны ловиться. «10х5х3»/«15х7х3» — габарит пропеллера, он же размер борта.
"""

import re

DRONE_SIZES = {7, 9, 10, 13, 15}  # дюймы

# Токены имени (lower), говорящие о размере борта.
# Хотфикс Д1: семейство «Mark4» — эталонные рамы 10″ («Рама карбон Mark4»
# в выгрузке 1С — 10-дюймовая); в выгрузке НЕТ моторов/пропов/прочего с
# «mark4» в имени, поэтому токен не даёт ложных срабатываний в других
# категориях (см. test_mark4_token_absent_outside_frames).
SIZE_TOKENS: dict[int, list[str]] = {
    7: ["7 дюймов", "для 7"],
    9: ["9 дюймов", "для 9"],
    10: ["10 дюймов", "для 10", "10х5х3", "10x5x3", "1050", "mark4", "марк4"],
    13: ["13 дюймов", "для 13", "13х9х3", "13x9x3", "13x10", "13?9?3"],
    15: ["15 дюймов", "для 15", "15х7х3", "15x7x3", "1510", "15?7?3"],
}

# Статоры моторов (после вылова регэкспом (\d{4})) по размеру борта.
# Производственная матрица Этапа 10: 5×10″, 3×13″, 4×15″ + 1 гексакоптер 15″
# (6 моторов, два ESC — Этап 10в): 4320 собран и на 13″, и на гекса-15″.
MOTOR_STATOR_BY_SIZE: dict[int, list[str]] = {
    9: ["3115"],
    10: ["3115"],
    13: ["4214", "4320"],
    15: ["5315", "4320"],
}

# Одиночное число размера в имени («Рама 10 МАРК4-V2»): не часть большего
# числа (3115, 1050, 900KV) и не начало десятичной дроби («7,5см»).
_BARE_SIZE_RE = re.compile(r"(?<!\d)(7|9|10|13|15)(?!\d)(?![.,]\d)")

# Статор мотора: четыре цифры подряд (3115 / 4214 / 4320 / 5315).
_STATOR_RE = re.compile(r"(\d{4})")


def detect_size(name: str) -> int | None:
    """Размер борта из названия: сначала явные токены, затем одиночное число.

    None — размер в имени не выражен.
    """
    s = str(name).lower()
    for size in sorted(DRONE_SIZES):
        if any(token in s for token in SIZE_TOKENS[size]):
            return size
    m = _BARE_SIZE_RE.search(s)
    return int(m[1]) if m else None


def extract_stator(name: str) -> str | None:
    """Статор мотора из имени («Мотор axisfly 4320 380KV» → «4320»); None если нет."""
    m = _STATOR_RE.search(str(name))
    return m[1] if m else None

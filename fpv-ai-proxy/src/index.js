function trimAnswer(answer, maxLen) {
  if (answer.length <= maxLen) return answer;

  let cut = answer.slice(0, maxLen);
  const lastBreak = Math.max(cut.lastIndexOf(" "), cut.lastIndexOf("\n"));
  if (lastBreak > maxLen * 0.6) {
    cut = cut.slice(0, lastBreak);
  }

  // Закрываем незакрытые теги
  const openB = (cut.match(/<b>/g) || []).length;
  const closeB = (cut.match(/<\/b>/g) || []).length;
  if (openB > closeB) cut += "</b>";

  const openI = (cut.match(/<i>/g) || []).length;
  const closeI = (cut.match(/<\/i>/g) || []).length;
  if (openI > closeI) cut += "</i>";

  return cut.trimEnd() + "…";
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (request.method === "GET") {
      return new Response("FPV AI proxy is running.");
    }

    if (request.method !== "POST") {
      return new Response("Method not allowed", { status: 405 });
    }

    if (!env.AI_PROXY_TOKEN) {
      return Response.json({ ok: false, error: "AI_PROXY_TOKEN is not set" }, { status: 500 });
    }

    const auth = request.headers.get("authorization") || "";
    if (auth !== `Bearer ${env.AI_PROXY_TOKEN}`) {
      return Response.json({ ok: false, error: "Unauthorized" }, { status: 401 });
    }

    // --- ЭНДПОИНТ ДЛЯ РАСПОЗНАВАНИЯ ГОЛОСА ---
    if (url.pathname === "/transcribe") {
      try {
        const audioData = await request.arrayBuffer();
        if (!audioData || audioData.byteLength === 0) {
          return Response.json({ ok: false, error: "Empty audio" }, { status: 400 });
        }

        const audioArray = Array.from(new Uint8Array(audioData));
        const whisperModel = env.WHISPER_MODEL || "@cf/openai/whisper";

        const result = await env.AI.run(whisperModel, {
          audio: audioArray
        });

        return Response.json({ ok: true, text: result.text || "" });
      } catch (error) {
        return Response.json({ ok: false, error: String(error) }, { status: 500 });
      }
    }

    // --- ОСНОВНОЙ ЭНДПОИНТ ДЛЯ ТЕКСТА ---
    let payload;
    try {
      payload = await request.json();
    } catch {
      return Response.json({ ok: false, error: "Invalid JSON body" }, { status: 400 });
    }

    const question = String(payload.question || "").slice(0, 3000);
    if (!question) {
      return Response.json({ ok: false, error: "question is required" }, { status: 400 });
    }

    try {
      // Определяем тип вопроса ДО вызова AI для корректного max_tokens
      const modelPattern = /\b\d+S\d+P\b/i;
      const isModelQuestion = modelPattern.test(question);
      const MAX_LEN = isModelQuestion ? 1200 : 700;

      const prompt = buildPrompt(question);
      const model = env.AI_MODEL || "@cf/meta/llama-3.3-70b-instruct-fp8-fast";

      const result = await env.AI.run(model, {
        prompt,
        max_tokens: isModelQuestion ? 400 : 280,
        temperature: 0.25,
      });

      let answer = "";
      if (typeof result === "string") answer = result;
      else if (result && result.response) answer = result.response;
      else if (result && result.message && result.message.content) answer = result.message.content;
      else answer = JSON.stringify(result);

      // ПОСТ-ОБРАБОТКА: обрезаем весь мусор до первого <b>💡 Вывод:</b>
      const startMarker = "<b>💡 Вывод:</b>";
      const startIndex = answer.indexOf(startMarker);

      if (startIndex !== -1) {
        answer = answer.substring(startIndex);
      } else {
        answer = startMarker + "\n" + answer;
      }

      // ПОСТ-ОБРАБОТКА: удаляем пустые/лишние секции "🚩 Красные флаги"
      const flagPatterns = [
        /<b>🚩\s*Красные флаги:?<\/b>\s*$/i,
        /<b>🚩\s*Красные флаги:?<\/b>\s*(нет|отсутствуют|не выявлено|стоп-факторов нет)\.?/gi
      ];
      for (const p of flagPatterns) {
        answer = answer.replace(p, "").trimEnd();
      }

      // ПОСТ-ОБРАБОТКА: удаляем секцию красных флагов целиком если > 3 пунктов
      answer = answer.replace(
        /(<b>🚩\s*Красные флаги:?<\/b>)([\s\S]*?)(?=<b>[^<]|$)/gi,
        (match, header, content) => {
          const lines = content.trim().split('\n').filter(l => l.trim());
          return lines.length > 3 ? '' : match;
        }
      );

      // ПОСТ-ОБРАБОТКА: деградация модели — зацикливание на маркере секции.
      // Повторные ПУСТЫЕ "<b>💡 Вывод:</b>" удаляем (остаются только маркеры
      // с контентом), затем срезаем пустые маркеры в хвосте ответа.
      answer = answer.replace(
        /(<b>💡 Вывод:<\/b>)([\s\S]*?)(?=<b>💡 Вывод:<\/b>|$)/gi,
        (match, head, content) => (content.trim() ? match : "")
      );
      answer = answer.replace(/(?:\s*<b>💡 Вывод:<\/b>)+\s*$/i, "").trimEnd();

      // ПОСТ-ОБРАБОТКА: универсальная очистка зацикливаний на "золотых фразах"
      answer = answer.replace(
        /[\s\S]*?(?:золот(?:ые|ых|ыми)\s+фраз(?:ы|ам|ами)[\s\S]*)$/i, ""
      ).trimEnd();

      // ПОСТ-ОБРАБОТКА: убираем шаблонные призывы в конце
      answer = answer.replace(
        /[\s\S]*?(?:Это поможет|Помните|Всегда помните|Удачи в продажах|Хороших продаж)[\s\S]*$/i, ""
      ).trimEnd();

      // ФИНАЛЬНАЯ обрезка по лимиту символов
      answer = trimAnswer(answer, MAX_LEN);

      // ПОСТ-ОБРАБОТКА: наружу не отдаём «ответ», который на самом деле
      // ошибка бэкенда (невалидный ключ и т.п.) либо пуст после очистки:
      // бот получит 502 и покажет менеджеру мягкую фразу-заглушку.
      const errorLeak = /\b(unauthorized|unauthenticated|invalid api key|authentication error|quota exceeded|internal server error|bad gateway|service unavailable|gateway timeout)\b/i.test(answer);
      const noContent = !answer.replace(/<[^>]+>/g, "").replace(/[\s…]/g, "").length;
      if (errorLeak || noContent) {
        return Response.json(
          {
            ok: false,
            error: errorLeak
              ? "AI model returned an error instead of an answer"
              : "AI model produced no usable answer",
          },
          { status: 502 }
        );
      }

      return Response.json({ ok: true, answer: answer.trim(), model });
    } catch (error) {
      return Response.json({ ok: false, error: String(error) }, { status: 500 });
    }
  },
};
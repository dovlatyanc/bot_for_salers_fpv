export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (request.method === "GET") {
      return new Response("FPV AI proxy is running.");
    }

    if (request.method !== "POST") {
      return new Response("Method not allowed", { status: 405 });
    }

    if (!env.AI_PROXY_TOKEN) {
      return Response.json({ ok: false, error: "AI_PROXY_TOKEN is not set" }, { status: 500 });
    }

    const auth = request.headers.get("authorization") || "";
    if (auth !== `Bearer ${env.AI_PROXY_TOKEN}`) {
      return Response.json({ ok: false, error: "Unauthorized" }, { status: 401 });
    }

    // --- ЭНДПОИНТ ДЛЯ РАСПОЗНАВАНИЯ ГОЛОСА ---
    if (url.pathname === "/transcribe") {
      try {
        const audioData = await request.arrayBuffer();
        if (!audioData || audioData.byteLength === 0) {
          return Response.json({ ok: false, error: "Empty audio" }, { status: 400 });
        }

        const audioArray = Array.from(new Uint8Array(audioData));
        const whisperModel = env.WHISPER_MODEL || "@cf/openai/whisper";
        
        const result = await env.AI.run(whisperModel, {
          audio: audioArray
        });

        return Response.json({ ok: true, text: result.text || "" });
      } catch (error) {
        return Response.json({ ok: false, error: String(error) }, { status: 500 });
      }
    }

    // --- ОСНОВНОЙ ЭНДПОИНТ ДЛЯ ТЕКСТА ---
    let payload;
    try {
      payload = await request.json();
    } catch {
      return Response.json({ ok: false, error: "Invalid JSON body" }, { status: 400 });
    }

    const question = String(payload.question || "").slice(0, 3000);
    if (!question) {
      return Response.json({ ok: false, error: "question is required" }, { status: 400 });
    }

    try {
      const prompt = buildPrompt(question);
      const model = env.AI_MODEL || "@cf/meta/llama-3.3-70b-instruct-fp8-fast";

      const result = await env.AI.run(model, {
        prompt,
        max_tokens: 600,
        temperature: 0.05,
      });

      let answer = "";
      if (typeof result === "string") answer = result;
      else if (result && result.response) answer = result.response;
      else if (result && result.message && result.message.content) answer = result.message.content;
      else answer = JSON.stringify(result);

      // ПОСТ-ОБРАБОТКА: обрезаем весь мусор до первого <b>💡 Вывод:</b>
      const startMarker = "<b>💡 Вывод:</b>";
      const startIndex = answer.indexOf(startMarker);
      
      if (startIndex !== -1) {
        answer = answer.substring(startIndex);
      } else {
        // Если модель забыла маркер, добавляем его в начало
        answer = startMarker + "\n" + answer;
      }

      // ПОСТ-ОБРАБОТКА: удаляем пустые/лишние секции "🚩 Красные флаги"
      // (модель иногда пишет секцию без содержания или с шаблонной водой)
      const flagPatterns = [
        /<b>🚩\s*Красные флаги:?<\/b>\s*$/i,          // пустая секция в конце
        /<b>🚩\s*Красные флаги:?<\/b>\s*(нет|отсутствуют|не выявлено|стоп-факторов нет)\.?/gi
      ];
      for (const p of flagPatterns) {
        answer = answer.replace(p, "").trimEnd();
      }

      return Response.json({ ok: true, answer: answer.trim(), model });
    } catch (error) {
      return Response.json({ ok: false, error: String(error) }, { status: 500 });
    }
  },
};
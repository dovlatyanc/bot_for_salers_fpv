def _resolve_key(objection_type: str) -> str | None:
    # NEW: ключ ищется и по коду ("expensive"), и по подписи кнопки ("Дорого", "дорого")
    if not objection_type:
        return None
    needle = objection_type.strip().lower()
    if needle in OBJECTIONS:
        return needle
    for key, item in OBJECTIONS.items():
        if item["label"].lower() == needle:
            return key
    return None


def get_objection_labels() -> list[tuple[str, str]]:
    """[(key, label), ...] в порядке кнопок экрана «💬 Возражения»."""
    return [(key, item["label"]) for key, item in OBJECTIONS.items()]


def get_objection_response(objection_type: str) -> str:
    """
    Скрипт ответа на возражение в виде HTML-текста для Telegram.

    objection_type — ключ возражения ("expensive") или подпись кнопки ("Дорого").
    Неизвестное возражение → подсказка со списком доступных (без исключений).
    """
    key = _resolve_key(objection_type)
    if key is None:
        available = "\n".join(f"• {item['label']}" for item in OBJECTIONS.values())
        return (
            f"Скрипт для возражения «{str(objection_type).strip()}» не найден.\n\n"
            f"<b>Доступные возражения:</b>\n{available}"
        )

    item = OBJECTIONS[key]
    lines = [f"💬 <b>{item['label']}</b>", "", "<b>Ключевые тезисы:</b>"]
    lines += [f"• {thesis}" for thesis in item["theses"]]
    lines += ["", "<b>Варианты ответа:</b>"]
    lines += [f"{i}. {script}" for i, script in enumerate(item["scripts"], 1)]
    lines += [
        "",
        "<i>Порядок разговора: вопрос → выявление причины → аргумент по фактам → конкретный "
        "следующий шаг. Формулировки адаптируйте под клиента.</i>",
    ]
    return "\n".join(lines)
